using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace JPCenter.Modules.System.Infrastructure.Persistence.Configurations;

/// <summary>system.user_sessions — database.md bảng 13a.</summary>
internal sealed class UserSessionConfiguration : IEntityTypeConfiguration<UserSession>
{
    public void Configure(EntityTypeBuilder<UserSession> b)
    {
        b.ToTable("user_sessions");
        b.HasKey(x => x.Id);
        b.HasIndex(x => x.RefreshTokenHash).IsUnique();
        b.HasIndex(x => x.PreviousTokenHash);
        b.HasIndex(x => new { x.AccountKind, x.AccountId });
    }
}
